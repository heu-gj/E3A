"""HOI4D 2D motion-mask decoding and clip-level entity targets.

The palette and category/instance tables below follow the official
HOI4D_Script/prepare_4Dseg/palette.py and utils.py implementation. The reader
keeps the official category-specific palette semantics and treats missing mask
files as unannotated rather than as negative masks.
"""

from __future__ import annotations

from collections.abc import Sequence

import numpy as np
import torch


# Official HOI4D 4D-segmentation mappings. Entry i corresponds to palette color i+1.
_CATEGORY_TO_SEMANTIC: dict[str, tuple[int, ...]] = {
    "C1": (24, 47),
    "C2": (17, 47, 17),
    "C3": (25, 47, 25),
    "C4": (19, 47, 19, 19, 16),
    "C5": (16, 47, 17),
    "C6": (27, 47, 27, 16),
    "C7": (15, 47, 46),
    "C8": (9, 47, 9, 9, 9, 47),
    "C9": (48, 47, 48),
    "C10": (22, 47),
    "C11": (23, 47, 23),
    "C12": (21, 47, 17),
    "C13": (31, 47, 46),
    "C14": (10, 47, 10, 16),
    "C15": (20, 47, 20, 20, 20, 20),
    "C16": (30, 47, 30, 30),
    "C17": (29, 47, 29, 29, 29, 47),
    "C18": (28, 47, 28, 28, 46),
    "C19": (26, 47, 26, 26, 26, 26),
    "C20": (2, 47, 47),
}
_CATEGORY_TO_INSTANCE: dict[str, tuple[int, ...]] = {
    "C1": (1, 2),
    "C2": (1, 2, 3),
    "C3": (1, 2, 1),
    "C4": (1, 2, 1, 1, 3),
    "C5": (1, 2, 3),
    "C6": (1, 2, 1, 3),
    "C7": (1, 2, 3),
    "C8": (1, 2, 1, 3, 3, 4),
    "C9": (1, 2, 1),
    "C10": (1, 2),
    "C11": (1, 2, 1),
    "C12": (1, 2, 3),
    "C13": (1, 2, 3),
    "C14": (1, 2, 1, 3),
    "C15": (1, 2, 1, 1, 1, 1),
    "C16": (1, 2, 1, 1),
    "C17": (1, 2, 1, 1, 1, 3),
    "C18": (1, 2, 1, 1, 3),
    "C19": (1, 2, 1, 1, 1, 1),
    "C20": (1, 2, 3),
}
HOI4D_HAND_SEMANTIC_ID = 47


def hoi4d_color_palette(size: int = 256) -> np.ndarray:
    """Return the exact RGB palette generated by the official HOI4D script."""
    if size <= 0 or size > 256:
        raise ValueError("HOI4D palette size must be in [1,256].")
    palette = np.zeros((size, 3), dtype=np.uint8)
    for index in range(size):
        red = green = blue = 0
        value = index
        for bit in range(8):
            red |= ((value >> 0) & 1) << (7 - bit)
            green |= ((value >> 1) & 1) << (7 - bit)
            blue |= ((value >> 2) & 1) << (7 - bit)
            value >>= 3
        palette[index] = (red, green, blue)
    return palette


def decode_hoi4d_motion_mask(
    rgb_mask: np.ndarray,
    category: str,
) -> tuple[np.ndarray, np.ndarray]:
    """Decode an RGB palette mask into official semantic and instance maps.

    Args:
        rgb_mask: RGB uint8 image [H,W]. Do not pass OpenCV's BGR order.
        category: HOI4D category code, e.g. "C8".

    Returns:
        semantic_map: int16 [H,W], using official category semantic IDs.
        instance_map: int16 [H,W], using official category-local instance IDs.

    Palette index zero is background. Unknown non-background colors fail closed.
    """
    if category not in _CATEGORY_TO_SEMANTIC:
        raise ValueError(f"Unsupported HOI4D category code: {category!r}")
    if _CATEGORY_TO_SEMANTIC[category] == () or (
        len(_CATEGORY_TO_SEMANTIC[category]) != len(_CATEGORY_TO_INSTANCE[category])
    ):
        raise RuntimeError(f"Invalid built-in HOI4D palette mapping for {category}.")

    image = np.asarray(rgb_mask)
    if image.ndim != 3 or image.shape[-1] != 3:
        raise ValueError("rgb_mask must have shape [H,W,3].")
    if image.dtype != np.uint8:
        raise TypeError("rgb_mask must use uint8 RGB values.")

    semantic_ids = _CATEGORY_TO_SEMANTIC[category]
    instance_ids = _CATEGORY_TO_INSTANCE[category]
    palette = hoi4d_color_palette(max(len(semantic_ids) + 1, 1))

    semantic_map = np.zeros(image.shape[:2], dtype=np.int16)
    instance_map = np.zeros(image.shape[:2], dtype=np.int16)
    known = np.all(image == palette[0], axis=-1)

    for palette_index, (semantic_id, instance_id) in enumerate(
        zip(semantic_ids, instance_ids, strict=True),
        start=1,
    ):
        pixels = np.all(image == palette[palette_index], axis=-1)
        if pixels.any():
            semantic_map[pixels] = semantic_id
            instance_map[pixels] = instance_id
            known |= pixels

    if not known.all():
        unknown_colors = np.unique(image[~known].reshape(-1, 3), axis=0)
        preview = unknown_colors[:5].tolist()
        raise ValueError(
            "HOI4D mask contains colors not defined by the official category palette "
            f"for {category}: {preview}"
        )
    return semantic_map, instance_map


def build_hoi4d_entity_clip_targets(
    rgb_mask_frames: Sequence[np.ndarray | None],
    category: str,
) -> dict[str, torch.Tensor]:
    """Build object-only, clip-consistent entity targets from HOI4D motion masks.

    All non-hand semantic parts that share an official instance ID are merged
    into one entity mask. The official hand semantic class (47) is excluded
    because E3A has a separate two-hand pose head.

    A present mask file marks every track/frame as annotated. If a track is
    absent in that annotated frame, its ID is -1 with a zero mask. A missing
    mask file produces mask_valid=False for every track in that frame.
    """
    if not isinstance(rgb_mask_frames, Sequence) or len(rgb_mask_frames) == 0:
        raise ValueError("rgb_mask_frames must be a non-empty sequence.")

    decoded: list[tuple[np.ndarray, np.ndarray] | None] = []
    spatial_size: tuple[int, int] | None = None
    entity_ids: set[int] = set()

    for frame_index, frame in enumerate(rgb_mask_frames):
        if frame is None:
            decoded.append(None)
            continue
        semantic, instance = decode_hoi4d_motion_mask(frame, category)
        size = tuple(int(value) for value in semantic.shape)
        if spatial_size is None:
            spatial_size = size
        elif size != spatial_size:
            raise ValueError(
                f"HOI4D mask frame {frame_index} has size {size}, expected {spatial_size}."
            )
        object_pixels = (
            (semantic != HOI4D_HAND_SEMANTIC_ID)
            & (semantic != 0)
            & (instance > 0)
        )
        entity_ids.update(int(value) for value in np.unique(instance[object_pixels]))
        decoded.append((semantic, instance))

    if spatial_size is None:
        raise ValueError("At least one HOI4D mask frame must be available to infer image size.")

    ordered_ids = sorted(entity_ids)
    frame_count = len(rgb_mask_frames)
    entity_count = len(ordered_ids)
    height, width = spatial_size

    labels = torch.zeros(entity_count, dtype=torch.int64)
    track_ids = torch.full((entity_count, frame_count), -1, dtype=torch.int64)
    masks = torch.zeros((entity_count, frame_count, height, width), dtype=torch.float32)
    mask_valid = torch.zeros((entity_count, frame_count), dtype=torch.bool)

    for frame_index, frame_maps in enumerate(decoded):
        if frame_maps is None:
            continue
        semantic, instance = frame_maps
        object_pixels = (semantic != HOI4D_HAND_SEMANTIC_ID) & (semantic != 0)
        for entity_index, instance_id in enumerate(ordered_ids):
            binary_mask = object_pixels & (instance == instance_id)
            mask_valid[entity_index, frame_index] = True
            if binary_mask.any():
                track_ids[entity_index, frame_index] = instance_id
                masks[entity_index, frame_index] = torch.from_numpy(
                    binary_mask.astype(np.float32)
                )

    return {
        "labels": labels,
        "ids": track_ids,
        "masks": masks,
        "mask_valid": mask_valid,
    }
